-- 创建日常问答表
CREATE TABLE `daily_question` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `question` varchar(500) NOT NULL COMMENT '问题内容',
  `answer` text NOT NULL COMMENT '答案内容',
  `category` varchar(100) DEFAULT NULL COMMENT '问题分类',
  `create_time` datetime NOT NULL COMMENT '创建时间',
  `update_time` datetime NOT NULL COMMENT '更新时间',
  `status` int(1) NOT NULL DEFAULT '1' COMMENT '状态：1-启用，0-禁用',
  `sort_weight` int(11) DEFAULT '0' COMMENT '排序权重',
  `remark` varchar(500) DEFAULT NULL COMMENT '备注',
  PRIMARY KEY (`id`),
  KEY `idx_category` (`category`),
  KEY `idx_status` (`status`),
  KEY `idx_create_time` (`create_time`),
  KEY `idx_sort_weight` (`sort_weight`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='日常问答表';

